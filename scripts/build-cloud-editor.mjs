// Bundles the web app's formatted editor (cloud/web/editor-src/md-editor.mjs, CodeMirror 6) into cloud/web/editor.mjs;
// the cloud server serves only fixed files. The formatting core and the table grid stay outside the bundle: the page
// loads them as /shared/format.mjs and /shared/table-grid.mjs, the same files app.js and Obsidian use.
// The licence of every bundled package (all MIT) goes at the top of the output, as their licences ask.
import { build } from 'esbuild';
import { existsSync, readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export const source = resolve(root, 'cloud/web/editor-src/md-editor.mjs');
export const output = resolve(root, 'cloud/web/editor.mjs');

function packageOf(file) {
  for (let dir = dirname(resolve(root, file)); dir.startsWith(join(root, 'node_modules')); dir = dirname(dir)) {
    if (existsSync(join(dir, 'package.json'))) return dir;
  }
  return null;
}

export async function bundleCloudEditor() {
  const result = await build({
    entryPoints: [source],
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022', write: false, metafile: true, minify: true, legalComments: 'none',
    external: ['/shared/*'],
  });
  const licences = new Map();
  // Only what ends up in the bundle: a package that was read but left out entirely is not shipped.
  const used = Object.entries(Object.values(result.metafile.outputs)[0].inputs).filter(([, info]) => info.bytesInOutput > 0).map(([input]) => input);
  for (const input of used) {
    const dir = packageOf(input);
    if (!dir) continue;
    const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const file = ['LICENSE', 'LICENSE.md', 'LICENSE.txt'].map((name) => join(dir, name)).find(existsSync);
    if (!file) throw new Error(`No licence file for ${meta.name}`);
    const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim();
    const entry = licences.get(text) || { names: [], text };
    entry.names.push(`${meta.name}@${meta.version} (${meta.license})`);
    licences.set(text, entry);
  }
  const notice = [...licences.values()].map((entry) => `${entry.names.sort().join(', ')}:\n\n${entry.text}`).join('\n\n---\n\n');
  const banner = `// Generated by \`npm run build:cloud-editor\` from cloud/web/editor-src/md-editor.mjs. Do not edit.\n/*! Bundled packages and their licences:\n\n${notice.replace(/\*\//g, '* /')}\n*/\n`;
  return banner + result.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(output, await bundleCloudEditor());
  console.log(`Wrote ${output}`);
}
