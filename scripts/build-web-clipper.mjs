// Builds chrome-extension/cloud-client.js: chrome-extension/cloud.mjs with the shared cloud client and crypto
// (cloud/shared) bundled into one classic script for the popup and settings pages. The bundle is committed, so
// the store ZIP (scripts/package-web-clipper.mjs) is exactly the committed chrome-extension tree.
//   node scripts/build-web-clipper.mjs          write the bundle
//   node scripts/build-web-clipper.mjs --check  fail when the committed bundle is not the fresh build
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export const bundlePath = resolve(root, 'chrome-extension', 'cloud-client.js');

export async function buildWebClipperBundle() {
  const result = await build({
    entryPoints: [resolve(root, 'chrome-extension/cloud.mjs')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'chrome120',
    charset: 'utf8',
    legalComments: 'inline',
    write: false,
    banner: { js: '// Generated by scripts/build-web-clipper.mjs from chrome-extension/cloud.mjs and cloud/shared. Do not edit.' },
  });
  // Same bytes on every OS: esbuild writes \n, but keep it explicit for checkouts with autocrlf.
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fresh = await buildWebClipperBundle();
  if (process.argv.includes('--check')) {
    const committed = (await readFile(bundlePath, 'utf8').catch(() => '')).replace(/\r\n/g, '\n');
    if (committed !== fresh) {
      console.error('chrome-extension/cloud-client.js is out of date. Run: npm run build:web-clipper');
      process.exit(1);
    }
    console.log('chrome-extension/cloud-client.js matches a fresh build.');
  } else {
    await writeFile(bundlePath, fresh);
    console.log(`Built ${bundlePath} (${Buffer.byteLength(fresh)} bytes).`);
  }
}
