// Builds chrome-extension/cloud-client.js and chrome-extension/ai-client.js: chrome-extension/cloud.mjs with the shared
// cloud client and crypto (cloud/shared) and chrome-extension/ai.mjs with the shared AI providers, each bundled into one
// classic script for the popup and settings pages. The bundles are committed, so the store ZIP
// (scripts/package-web-clipper.mjs) is exactly the committed chrome-extension tree.
//   node scripts/build-web-clipper.mjs          write both bundles
//   node scripts/build-web-clipper.mjs --check  fail when a committed bundle is not the fresh build
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export const bundles = [
  { source: 'cloud.mjs', output: 'cloud-client.js' },
  { source: 'ai.mjs', output: 'ai-client.js' },
];
export const bundlePath = resolve(root, 'chrome-extension', 'cloud-client.js');

export async function buildWebClipperBundle(source = 'cloud.mjs') {
  const result = await build({
    entryPoints: [resolve(root, 'chrome-extension', source)],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'chrome120',
    charset: 'utf8',
    legalComments: 'inline',
    write: false,
    banner: { js: `// Generated by scripts/build-web-clipper.mjs from chrome-extension/${source} and cloud/shared. Do not edit.` },
  });
  // Same bytes on every OS: esbuild writes \n, but keep it explicit for checkouts with autocrlf.
  return result.outputFiles[0].text.replace(/\r\n/g, '\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let stale = false;
  for (const { source, output } of bundles) {
    const path = resolve(root, 'chrome-extension', output);
    const fresh = await buildWebClipperBundle(source);
    if (process.argv.includes('--check')) {
      const committed = (await readFile(path, 'utf8').catch(() => '')).replace(/\r\n/g, '\n');
      if (committed !== fresh) {
        console.error(`chrome-extension/${output} is out of date. Run: npm run build:web-clipper`);
        stale = true;
      } else console.log(`chrome-extension/${output} matches a fresh build.`);
    } else {
      await writeFile(path, fresh);
      console.log(`Built ${path} (${Buffer.byteLength(fresh)} bytes).`);
    }
  }
  if (stale) process.exit(1);
}
