// Bundles the plugin's note importers into cloud/web/import.mjs; the cloud server serves only fixed files.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export const output = resolve(root, 'cloud/web/import.mjs');

export async function bundleCloudImport() {
  const result = await build({
    entryPoints: [resolve(root, 'cloud/web/import-entry.ts')],
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022', write: false, legalComments: 'none',
    banner: { js: '// Generated by `npm run build:cloud-import` from cloud/web/import-entry.ts. Do not edit.' },
    plugins: [{
      name: 'obsidian-stub',
      setup(builder) {
        builder.onResolve({ filter: /^obsidian$/ }, () => ({ path: 'obsidian', namespace: 'stub' }));
        builder.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
          contents: 'export const getLanguage = () => "en"; export const normalizePath = (path) => path; export const requestUrl = () => { throw new Error("Not available in the browser."); };',
        }));
      },
    }],
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(output, await bundleCloudImport());
  console.log(`Wrote ${output}`);
}
